QList<Cookie> parseNetscape(const QString &text) {
    QList<Cookie> out;
    const QStringList lines = text.split(QRegularExpression(QStringLiteral("\r?\n")));
    for (QString raw : lines) {
        bool httpOnly = raw.startsWith(QStringLiteral("#HttpOnly_"));
        if (httpOnly) raw = raw.mid(10);
        if (raw.isEmpty() || (raw.startsWith('#') && !httpOnly)) continue;
        const QStringList p = raw.split('\t');
        if (p.size() < 7 || p[0].isEmpty() || p[5].isEmpty()) continue;
        bool ok = false;
        double exp = p[4].toDouble(&ok);
        if (!ok) continue;
        Cookie c;
        c.domain = p[0]; c.path = p[2].isEmpty() ? QStringLiteral("/") : p[2];
        c.secure = p[3].compare(QStringLiteral("TRUE"), Qt::CaseInsensitive) == 0;
        c.httpOnly = httpOnly; c.expires = exp > 0 ? exp : -1;
        c.name = p[5]; c.value = p.mid(6).join('\t');
        out.append(c);
    }
    return out;
}

QString serializeNetscape(const QList<Cookie> &cookies, const QString &header) {
    QStringList lines;
    lines << QStringLiteral("# Netscape HTTP Cookie File")
          << (header.isEmpty() ? QStringLiteral("# Generated by cool desktop app; keep private.") : header);
    for (const Cookie &c : cookies) {
        QString domain = c.domain; domain.replace(QRegularExpression(QStringLiteral("[\t\r\n]")), QStringLiteral(" "));
        domain = domain.trimmed();
        QString name = c.name; name.replace(QRegularExpression(QStringLiteral("[\t\r\n ]")), QStringLiteral("_"));
        QString value = c.value; value.replace(QRegularExpression(QStringLiteral("[\t\r\n]")), QStringLiteral(" "));
        QString path = c.path.isEmpty() ? QStringLiteral("/") : c.path;
        qint64 exp = c.expires > 0 ? qint64(c.expires) : 0;
        QString line = QStringLiteral("%1\t%2\t%3\t%4\t%5\t%6\t%7")
            .arg(domain, domain.startsWith('.') ? QStringLiteral("TRUE") : QStringLiteral("FALSE"), path,
                 c.secure ? QStringLiteral("TRUE") : QStringLiteral("FALSE"))
            .arg(exp).arg(name, value);
        lines << (c.httpOnly ? QStringLiteral("#HttpOnly_") + line : line);
    }
    return lines.join('\n') + QLatin1Char('\n');
}

static bool coolDomain(const QString &d0) {
    QString d = d0.toLower();
    if (d.startsWith('.')) d = d.mid(1);
    return d == QLatin1String("www.coolenglish.edu.tw") || d == QLatin1String("coolenglish.edu.tw");
}

QList<Cookie> coolCookies(const QList<Cookie> &all) {
    QList<Cookie> out;
    for (const Cookie &c : all) if (coolDomain(c.domain)) out.append(c);
    return out;
}

bool hasUsableMoodleSession(const QList<Cookie> &cookies) {
    const double now = QDateTime::currentSecsSinceEpoch();
    for (const Cookie &c : cookies)
        if (c.name == QLatin1String("MoodleSession") && !c.value.isEmpty() && coolDomain(c.domain)
            && (c.expires <= 0 || c.expires > now)) return true;
    return false;
}

QString cookieHeader(const QList<Cookie> &cookies) {
    const double now = QDateTime::currentSecsSinceEpoch();
    QStringList parts;
    for (const Cookie &c : cookies)
        if (c.expires <= 0 || c.expires > now) parts << c.name + QLatin1Char('=') + c.value;
    return parts.join(QStringLiteral("; "));
}

QString emailCookieName(const QString &email) {
    QString b = QString::fromLatin1(email.toUtf8().toBase64(QByteArray::Base64UrlEncoding | QByteArray::OmitTrailingEquals));
    return b.left(48) + QStringLiteral(".txt");
}

