QString protectString(const QString &plain) {
#ifdef Q_OS_WIN
    QByteArray in = plain.toUtf8();
    DATA_BLOB src{ DWORD(in.size()), reinterpret_cast<BYTE *>(in.data()) };
    DATA_BLOB dst{ 0, nullptr };
    if (!CryptProtectData(&src, L"cool", nullptr, nullptr, nullptr, CRYPTPROTECT_UI_FORBIDDEN, &dst))
        return QString();
    QByteArray out(reinterpret_cast<char *>(dst.pbData), int(dst.cbData));
    LocalFree(dst.pbData);
    return QString::fromLatin1(out.toBase64());
#else
    return QString::fromLatin1(plain.toUtf8().toBase64());
#endif
}

bool unprotectString(const QString &b64, QString *plain) {
    QByteArray in = QByteArray::fromBase64(b64.trimmed().toLatin1());
    if (in.isEmpty()) return false;
#ifdef Q_OS_WIN
    DATA_BLOB src{ DWORD(in.size()), reinterpret_cast<BYTE *>(in.data()) };
    DATA_BLOB dst{ 0, nullptr };
    if (!CryptUnprotectData(&src, nullptr, nullptr, nullptr, nullptr, CRYPTPROTECT_UI_FORBIDDEN, &dst))
        return false;
    if (plain) *plain = QString::fromUtf8(reinterpret_cast<char *>(dst.pbData), int(dst.cbData));
    SecureZeroMemory(dst.pbData, dst.cbData);
    LocalFree(dst.pbData);
    return true;
#else
    if (plain) *plain = QString::fromUtf8(in);
    return true;
#endif
}

