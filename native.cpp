QStringList cliMachineIds() {
    // Windows 上 CLI 的 _machine_key 沒有 /etc/machine-id，退化為 "{hostname}-{uuid.getnode()}"。
    QList<QPair<bool, QString>> macs;
    for (const QNetworkInterface &ni : QNetworkInterface::allInterfaces()) {
        if (ni.flags().testFlag(QNetworkInterface::IsLoopBack)) continue;
        QString hw = ni.hardwareAddress();
        if (hw.size() != 17) continue;
        QString hex = hw.remove(':').toLower();
        bool local = (hex.left(2).toInt(nullptr, 16) & 2) != 0;
        bool dup = false;
        for (auto &p : macs) if (p.second == hex) dup = true;
        if (!dup) macs.append({ local, hex });
    }
    std::stable_sort(macs.begin(), macs.end(), [](auto &a, auto &b) { return int(a.first) < int(b.first); });
    QStringList ids;
    QString host = QHostInfo::localHostName();
    for (auto &p : macs) ids << host + QLatin1Char('-') + QString::number(p.second.toULongLong(nullptr, 16));
    return ids;
}

static QByteArray xorWith(const QByteArray &data, const QString &machineId) {
    QByteArray key = QCryptographicHash::hash((machineId + QStringLiteral("cool_salt_v1")).toUtf8(), QCryptographicHash::Sha256);
    QByteArray out = data;
    for (int i = 0; i < out.size(); ++i) out[i] = char(uchar(out[i]) ^ uchar(key[i % key.size()]));
    return out;
}

bool decryptCliPassword(const QString &enc, int length, QString *out) {
    QByteArray cipher = QByteArray::fromBase64(enc.toLatin1());
    if (cipher.isEmpty()) return false;
    for (const QString &id : cliMachineIds()) {
        QByteArray plain = xorWith(cipher, id);
        QString s = QString::fromUtf8(plain);
        if (s.toUtf8() != plain) continue;           // 不是合法 UTF-8
        const QList<uint> cps = s.toUcs4();
        if (cps.isEmpty() || cps.size() > 512) continue;
        bool bad = false;
        for (uint cp : cps) if (cp <= 31 || cp == 127) { bad = true; break; }
        if (bad || (length > 0 && cps.size() != length)) continue;
        if (out) *out = s;
        return true;
    }
    return false;
}

QString encryptCliPassword(const QString &plain) {
    QStringList ids = cliMachineIds();
    if (ids.isEmpty()) return QString();
    return QString::fromLatin1(xorWith(plain.toUtf8(), ids.first()).toBase64());
}

