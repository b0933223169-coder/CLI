QString redactUrl(const QString &raw) {
    QUrl u(raw);
    if (!u.isValid() || u.scheme().isEmpty()) return raw;
    static const QRegularExpression sens(QStringLiteral("pass|token|secret|cookie|auth|session|csrf|code|state|signature"), QRegularExpression::CaseInsensitiveOption);
    if (u.hasQuery()) {
        QUrlQuery q(u);
        QUrlQuery nq;
        for (auto &kv : q.queryItems(QUrl::FullyDecoded))
            nq.addQueryItem(kv.first, sens.match(kv.first).hasMatch() ? QStringLiteral("[REDACTED]") : kv.second);
        u.setQuery(nq);
    }
    u.setFragment(QString());
    u.setUserName(QString()); u.setPassword(QString());
    return u.toString(QUrl::FullyEncoded);
}

QJsonObject redactHeaders(const QJsonObject &h) {
    static const QRegularExpression sens(QStringLiteral("authorization|cookie|token|secret|password|session|api[-_]key"), QRegularExpression::CaseInsensitiveOption);
    QJsonObject out;
    for (auto it = h.begin(); it != h.end(); ++it)
        out[it.key()] = sens.match(it.key()).hasMatch() ? QJsonValue(QStringLiteral("[REDACTED]")) : QJsonValue(it.value().toVariant().toString());
    return out;
}

QString humanSize(qint64 b) {
    if (b < 1024) return QStringLiteral("%1 B").arg(b);
    if (b < 1024 * 1024) return QStringLiteral("%1 KB").arg(b / 1024.0, 0, 'f', 1);
    return QStringLiteral("%1 MB").arg(b / 1048576.0, 0, 'f', 1);
}

bool atomicWrite(const QString &path, const QByteArray &data) {
    QDir().mkpath(QFileInfo(path).absolutePath());
    QSaveFile f(path);
    if (!f.open(QIODevice::WriteOnly)) return false;
    f.write(data);
    return f.commit();
}

QString sha256Hex(const QByteArray &b) {
    return QString::fromLatin1(QCryptographicHash::hash(b, QCryptographicHash::Sha256).toHex());
}

