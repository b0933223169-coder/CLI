bool isCoolUrl(const QString &raw) {
    QUrl u(raw);
    return u.scheme() == QLatin1String("https")
        && (u.host() == QLatin1String("www.coolenglish.edu.tw") || u.host() == QLatin1String("coolenglish.edu.tw"));
}
bool isGoogleAccountsUrl(const QString &raw) {
    QString h = QUrl(raw).host().toLower();
    return h == QLatin1String("accounts.google.com") || h.endsWith(QLatin1String(".accounts.google.com"))
        || h == QLatin1String("accounts.google.com.tw");
}
bool isGoogleRecaptchaUrl(const QString &raw) {
    QUrl u(raw);
    QString h = u.host().toLower(), p = u.path();
    static const QRegularExpression re(QStringLiteral("^/recaptcha(/|$)"), QRegularExpression::CaseInsensitiveOption);
    bool g = h == QLatin1String("google.com") || h.endsWith(QLatin1String(".google.com"))
          || h == QLatin1String("recaptcha.net") || h.endsWith(QLatin1String(".recaptcha.net"));
    return g && re.match(p).hasMatch();
}
bool isGoogleOAuthProviderHref(const QString &href) {
    QUrl base(QStringLiteral("https://www.coolenglish.edu.tw"));
    QUrl u = base.resolved(QUrl(href));
    if (u.host() != QLatin1String("www.coolenglish.edu.tw") || u.scheme() != QLatin1String("https")) return false;
    if (u.path().compare(QStringLiteral("/auth/oauth2/login.php"), Qt::CaseInsensitive) != 0) return false;
    return QUrlQuery(u).queryItemValue(QStringLiteral("id")) == QLatin1String("2");
}

static bool loginRoute(const QString &path) {
    static const QRegularExpression re(QStringLiteral("^/(?:login(?:/|\\.php|$)|auth(?:/|$))"),
                                       QRegularExpression::CaseInsensitiveOption);
    return re.match(path).hasMatch();
}
static bool hasLoginForm(const QString &html) {
    static const QRegularExpression a(QStringLiteral("<input\\b[^>]*(?:type=[\"']password[\"']|name=[\"']username[\"'])"),
                                      QRegularExpression::CaseInsensitiveOption);
    static const QRegularExpression b(QStringLiteral("<form\\b[^>]*id=[\"']login[\"']"),
                                      QRegularExpression::CaseInsensitiveOption);
    return a.match(html).hasMatch() || b.match(html).hasMatch();
}

bool isAuthenticatedDashboard(const QString &rawUrl, int status, const QString &html) {
    QUrl url(rawUrl);
    if (!url.isValid() || !isCoolUrl(rawUrl) || status < 200 || status >= 400) return false;
    const QString path = url.path();
    if (loginRoute(path)) return false;
    const QRegularExpression::PatternOption ci = QRegularExpression::CaseInsensitiveOption;
    static const QRegularExpression logout(QStringLiteral("logout\\.php|登出"), ci);
    bool hasLogout = logout.match(html).hasMatch();
    static const QRegularExpression profilePath(QStringLiteral("/user/profile\\.php$"), ci);
    static const QRegularExpression formRe(QStringLiteral("<form\\b"), ci);
    static const QRegularExpression gate(QStringLiteral("firstname|lastname|gender|birthday|phone|mobile|請填寫|verification|complete profile"), ci);
    if (profilePath.match(path).hasMatch() && formRe.match(html).hasMatch() && gate.match(html).hasMatch() && !hasLogout)
        return false;
    static const QRegularExpression uid(QStringLiteral("[\"']userId[\"']\\s*:\\s*(\\d+)"), ci);
    auto m = uid.match(html);
    qint64 userId = m.hasMatch() ? m.captured(1).toLongLong() : 0;
    static const QRegularExpression dash(QStringLiteral("^/(?:my/?)?$"), ci);
    bool isDash = dash.match(path).hasMatch();
    if (hasLogout) return true;
    if (hasLoginForm(html)) return false;
    static const QRegularExpression hints(QStringLiteral("log-out|log_out|個人檔案|time_view_detail_by_people\\.php"), ci);
    return (isDash && userId > 1) || hints.match(html).hasMatch();
}

QString classifyTimeReport(const QString &rawUrl, int status, const QString &html) {
    QUrl url(rawUrl);
    if (!url.isValid() || url.host().isEmpty()) return QStringLiteral("unknown");
    bool onCool = isCoolUrl(rawUrl);
    static const QRegularExpression tokens(QStringLiteral("logintoken|loginredirect"), QRegularExpression::CaseInsensitiveOption);
    if ((!onCool && url.host().contains(QLatin1String("accounts.google.com"), Qt::CaseInsensitive))
        || (onCool && loginRoute(url.path())) || tokens.match(html).hasMatch() || hasLoginForm(html))
        return QStringLiteral("expired");
    if (!onCool || status < 200 || status >= 400) return QStringLiteral("unknown");
    static const QRegularExpression table(QStringLiteral("<table\\b[^>]*id=[\"']sort-table[\"'][^>]*>"), QRegularExpression::CaseInsensitiveOption);
    static const QRegularExpression cells(QStringLiteral("<tbody\\b[^>]*>[\\s\\S]*?<tr\\b[^>]*>[\\s\\S]*?<td\\b[^>]*>[\\s\\S]*?<td\\b[^>]*>[\\s\\S]*?<td\\b[^>]*>[\\s\\S]*?<td\\b"), QRegularExpression::CaseInsensitiveOption);
    return (table.match(html).hasMatch() && cells.match(html).hasMatch()) ? QStringLiteral("valid") : QStringLiteral("unknown");
}

static QString decodeEntities(QString s) {
    static const QRegularExpression re(QStringLiteral("&(#x[\\da-f]+|#\\d+|amp|lt|gt|quot|apos|nbsp);"), QRegularExpression::CaseInsensitiveOption);
    QString out; int last = 0;
    auto it = re.globalMatch(s);
    while (it.hasNext()) {
        auto m = it.next();
        out += s.mid(last, m.capturedStart() - last);
        QString code = m.captured(1).toLower();
        QString rep = m.captured(0);
        if (code == "amp") rep = "&"; else if (code == "lt") rep = "<"; else if (code == "gt") rep = ">";
        else if (code == "quot") rep = "\""; else if (code == "apos") rep = "'"; else if (code == "nbsp") rep = " ";
        else {
            bool ok = false;
            uint cp = code.startsWith("#x") ? code.mid(2).toUInt(&ok, 16) : code.mid(1).toUInt(&ok, 10);
            if (ok && cp <= 0x10ffff) rep = QString::fromUcs4(reinterpret_cast<const char32_t *>(&cp), 1);
        }
        out += rep; last = m.capturedEnd();
    }
    out += s.mid(last);
    return out;
}

static QString cellText(QString h) {
    h.replace(QRegularExpression(QStringLiteral("<br\\s*/?>"), QRegularExpression::CaseInsensitiveOption), QStringLiteral(" "));
    h.replace(QRegularExpression(QStringLiteral("</(?:div|p|li)>"), QRegularExpression::CaseInsensitiveOption), QStringLiteral(" "));
    h.replace(QRegularExpression(QStringLiteral("<[^>]*>")), QStringLiteral(" "));
    h = decodeEntities(h);
    h.replace(QRegularExpression(QStringLiteral("\\s+")), QStringLiteral(" "));
    return h.trimmed();
}

int durationMinutes(const QString &t) {
    static const QRegularExpression h(QStringLiteral("(\\d+)\\s*小時")), m(QStringLiteral("(\\d+)\\s*分鐘"));
    auto a = h.match(t), b = m.match(t);
    return (a.hasMatch() ? a.captured(1).toInt() : 0) * 60 + (b.hasMatch() ? b.captured(1).toInt() : 0);
}

QList<ReportRow> parseTimeReport(const QString &html) {
    QList<ReportRow> rows;
    static const QRegularExpression tbl(QStringLiteral("<table\\b(?=[^>]*\\bid=[\"']sort-table[\"'])[^>]*>([\\s\\S]*?)</table>"), QRegularExpression::CaseInsensitiveOption);
    auto tm = tbl.match(html);
    if (!tm.hasMatch()) return rows;
    static const QRegularExpression tr(QStringLiteral("<tr\\b[^>]*>([\\s\\S]*?)</tr>"), QRegularExpression::CaseInsensitiveOption);
    static const QRegularExpression td(QStringLiteral("<td\\b[^>]*>([\\s\\S]*?)</td>"), QRegularExpression::CaseInsensitiveOption);
    auto rit = tr.globalMatch(tm.captured(1));
    while (rit.hasNext()) {
        auto r = rit.next();
        QStringList cells;
        auto cit = td.globalMatch(r.captured(1));
        while (cit.hasNext()) cells << cellText(cit.next().captured(1));
        if (cells.size() < 4) continue;
        ReportRow row;
        row.month = cells[0].replace('/', '-');
        row.platform = durationMinutes(cells[1]);
        row.video = durationMinutes(cells[2]);
        row.practice = durationMinutes(cells[3]);
        rows.append(row);
    }
    return rows;
}

QString detectUserId(const QString &html) {
    static const QRegularExpression a(QStringLiteral("time_view_detail_by_people\\.php\\?id=(\\d+)"));
    static const QRegularExpression b(QStringLiteral("[\"']userId[\"']\\s*:\\s*(\\d+)"));
    static const QRegularExpression c(QStringLiteral("user/profile\\.php\\?id=(\\d+)"));
    for (const QRegularExpression *re : {&a, &b, &c}) {
        auto m = re->match(html);
        if (m.hasMatch()) {
            QString id = m.captured(1);
            if (id != QLatin1String("0") && id != QLatin1String("1")) return id;
        }
    }
    return QString();
}

